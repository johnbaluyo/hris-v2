<?php

use App\Http\Controllers\AttendanceController;
use App\Http\Controllers\AttendanceReviewController;
use App\Http\Controllers\CalendarController;
use App\Http\Controllers\EmployeeLookupController;
use App\Http\Controllers\IntegrationController;
use App\Http\Controllers\PdsController;
use App\Http\Controllers\PortalController;
use App\Http\Controllers\PrivateFileController;
use App\Http\Controllers\StaffController;
use Illuminate\Support\Facades\Route;

Route::middleware(['auth', 'verified'])->group(function () {
    Route::get('/employees/lookup', EmployeeLookupController::class);
    Route::get('/ssi', [PortalController::class, 'index'])->name('ssi');
    Route::get('/hr/staff', [StaffController::class, 'index'])->name('staff.index');
    Route::get('/hr/staff/data', [StaffController::class, 'data']);
    Route::post('/hr/staff', [StaffController::class, 'store']);
    Route::get('/hr/staff/{employee}', [StaffController::class, 'show'])->whereNumber('employee');
    Route::put('/hr/staff/{employee}', [StaffController::class, 'update'])->whereNumber('employee');
    Route::patch('/hr/staff/{employee}/archive', [StaffController::class, 'archive']);
    Route::get('/hr/staff/{employee}/service-record', [StaffController::class, 'serviceRecord']);
    Route::get('/hr/staff/{employee}/service-record/print', [StaffController::class, 'printServiceRecord']);
    Route::get('/hr/staff/{employee}/history', [StaffController::class, 'serviceRecord']);
    Route::match(['get', 'post'], '/organization/{kind}', [StaffController::class, 'organization'])->whereIn('kind', ['divisions', 'positions'])->name('organization');
    Route::match(['get', 'post'], '/delegations', [StaffController::class, 'delegations'])->name('delegations');
    Route::get('/profile', [PdsController::class, 'index'])->name('pds.index');
    Route::get('/profile/{employee}', [PdsController::class, 'index'])->whereNumber('employee');
    Route::get('/profile/{employee}/print', [PdsController::class, 'print']);
    Route::get('/profile/{employee}/{section}/data', [PdsController::class, 'data']);
    Route::post('/profile/{employee}/{section}', [PdsController::class, 'save']);
    Route::put('/profile/{employee}/{section}/{entry}', [PdsController::class, 'save'])->whereNumber('entry');
    Route::delete('/profile/{employee}/{section}/{entry}', [PdsController::class, 'destroy'])->whereNumber('entry');
    Route::get('/employees/{employee}/files', [PrivateFileController::class, 'index']);
    Route::post('/employees/{employee}/files', [PrivateFileController::class, 'store']);
    Route::get('/files/{file}', [PrivateFileController::class, 'download'])->name('files.download');
    Route::get('/portal/manage', [PortalController::class, 'manage'])->name('portal.manage');
    Route::get('/portal/data', [PortalController::class, 'data']);
    Route::post('/portal/items', [PortalController::class, 'save']);
    Route::put('/portal/items/{item}', [PortalController::class, 'save']);
    Route::delete('/portal/items/{item}', [PortalController::class, 'destroy']);
    Route::get('/calendar', [CalendarController::class, 'index'])->name('calendar');
    Route::get('/calendar/data', [CalendarController::class, 'data']);
    Route::get('/calendar/feed', [CalendarController::class, 'feed']);
    Route::get('/calendar/events/{event}', [CalendarController::class, 'show']);
    Route::post('/calendar/events', [CalendarController::class, 'save']);
    Route::put('/calendar/events/{event}', [CalendarController::class, 'save']);
    Route::delete('/calendar/events/{event}', [CalendarController::class, 'destroy']);
    Route::get('/integration/runs', [IntegrationController::class, 'index']);
    Route::post('/integration/sync', [IntegrationController::class, 'store']);
    Route::get('/attendance', [AttendanceController::class, 'index'])->name('attendance');
    Route::get('/attendance/review', [AttendanceReviewController::class, 'index'])->name('attendance.review');
    Route::get('/attendance/review/data', [AttendanceReviewController::class, 'data']);
    Route::get('/attendance/review/export', [AttendanceReviewController::class, 'export']);
    Route::post('/attendance/clock', [AttendanceController::class, 'clock'])->middleware('throttle:6,1');
    Route::get('/attendance/{employee}', [AttendanceController::class, 'index'])->whereNumber('employee');
    Route::get('/attendance/{employee}/data', [AttendanceController::class, 'data']);
    Route::get('/attendance/{employee}/raw', [AttendanceController::class, 'raw']);
    Route::post('/attendance/{employee}/rebuild', [AttendanceController::class, 'rebuild']);
    Route::post('/attendance/{employee}/override', [AttendanceController::class, 'override']);
    Route::get('/attendance/{employee}/revisions/{attendance}', [AttendanceController::class, 'revisions']);
    Route::match(['get', 'post'], '/attendance/{employee}/remarks', [AttendanceController::class, 'remarks']);
    Route::get('/attendance/{employee}/report', [AttendanceController::class, 'report']);
});
